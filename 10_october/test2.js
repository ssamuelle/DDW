/* Vytvorte program, ktorý pomocou podmienky if...else skontroluje, či človek môže šoférovať auto.
Človek môže šoférovať, ak má 18 alebo viac rokov.
Vstupný údaj:
vek – napríklad 20 
Výstup:
Môže šoférovať. 
Nemôže šoférovať.
*/

let meno = "Samuel";
let vek = 14;

if (vek >= 18 ) {
    console.log(`${meno} moze soferovat.`);
}
else{
    console.log(`${meno} nemoze soferovat.`);
}
